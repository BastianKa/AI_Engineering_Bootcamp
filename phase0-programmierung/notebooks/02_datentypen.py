# Übung 2: Datentypen erkennen
# Lege drei Variablen an: eine ganze Zahl, eine Kommazahl, einen Wahrheitswert.
# Gib mit type(...) für jede den Typ aus.

zahl= 42
kommazahl = 1.5
wahrheitswer = True

typ_zahl = type(zahl)
typ_kommazahl = type(kommazahl)
typ_wahrheitswert = type(wahrheitswer)
print("Typ von zahl:", typ_zahl)
print("Typ von kommazahl:", typ_kommazahl)
print("Typ von wahrheitswer:", typ_wahrheitswert)
